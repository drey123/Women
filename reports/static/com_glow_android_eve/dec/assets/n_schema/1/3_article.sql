CREATE TABLE IF NOT EXISTS `article`(
	`id` INTEGER PRIMARY KEY,
	`category` INTEGER,
	`day` INTEGER,
	`external_id` STRING,
	`intro` STRING,
	`postpartum` INTEGER,
	`source` STRING,
	`thumbnail` STRING,
	`time_approved` INTEGER,
	`time_modified` INTEGER,
	`time_removed` INTEGER,
	`time_created` INTEGER NOT NULL,
	`title` STRING,
	`trimester` INTEGER,
	`type` STRING,
	`url` STRING,
	`week` INTEGER,
	`user_id` INTEGER
	);